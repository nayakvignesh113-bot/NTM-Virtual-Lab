# Builds src/narr.js (clip counts and durations) from audio/manifest.json. Run from the repository root.
import json
m=json.load(open('audio/manifest.json'))
open('src/narr.js','w').write('// Generated by tools/narration/make_narr.py. Clip count, number of principle paragraphs and clip durations (s) per process.\nconst NARR='+json.dumps(m,separators=(',',':'))+';\n')
print('src/narr.js:',len(m),'processes')
